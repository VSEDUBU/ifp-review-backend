def extract_pdf_text(pdf_file) -> str:
    """從 PDF 提取文本"""
    try:
        text = ""
        with pdfplumber.open(pdf_file) as pdf:
            for page in pdf.pages:
                text += page.extract_text() + "\n"
        return text
    except Exception as e:
        logger.error(f"PDF 提取失敗: {str(e)}")
        return ""

def call_openrouter_api(system_prompt: str, user_prompt: str) -> str:
    """調用 OpenRouter API"""
    try:
        headers = {
            'Authorization': f'Bearer {OPENROUTER_API_KEY}',
            'Content-Type': 'application/json',
        }

        data = {
            'model': 'meta-llama/llama-2-70b-chat',
            'messages': [
                {'role': 'system', 'content': system_prompt},
                {'role': 'user', 'content': user_prompt}
            ],
            'temperature': 0.7,
            'max_tokens': 4000
        }

        response = requests.post(OPENROUTER_API_URL, json=data, headers=headers, timeout=60)
        response.raise_for_status()

        result = response.json()
        if 'choices' in result and len(result['choices']) > 0:
            return result['choices'][0]['message']['content']
        return ""
    except Exception as e:
        logger.error(f"API 請求失敗: {str(e)}")
        return ""

# ===== 報告導出基類 =====
class ReportExporter(ABC):
    def __init__(self, data: dict, language: str = 'zh_TW'):
        self.data = data
        self.language = language
        self.lang = LANGUAGES.get(language, LANGUAGES['zh_TW'])
    
    @abstractmethod
    def export(self) -> tuple:
        """導出報告，返回 (二進制數據, 文件名)"""
        pass
    
    def get_verdict_text(self, verdict: str) -> str:
        """獲取判定文本"""
        verdict_map = {
            'PASS': self.lang['pass'],
            'FAIL': self.lang['fail'],
            'WARN': self.lang['warn'],
            'CONTRADICTION': self.lang['contradiction'],
            'MANUAL_REVIEW': self.lang['manual_review'],
        }
        return verdict_map.get(verdict, verdict)

