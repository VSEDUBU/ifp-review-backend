@app.route('/api/review', methods=['POST'])
def review_report():
    """上傳 PDF 並進行自動審核"""
    try:
        if 'file' not in request.files:
            return jsonify({'status': 'error', 'message': '缺少文件'}), 400

        file = request.files['file']
        if file.filename == '' or not file.filename.endswith('.pdf'):
            return jsonify({'status': 'error', 'message': '只支持 PDF 文件'}), 400

        report_type = request.form.get('type', 'AUTO')
        stage = request.form.get('stage', 'DVT')

        logger.info(f"開始審核: {file.filename}")

        pdf_text = extract_pdf_text(file.stream)
        if not pdf_text:
            return jsonify({'status': 'error', 'message': 'PDF 文本提取失敗'}), 400

        # RD 級審核框架
        system_prompt = f"""你是資深硬體工程師，負責審核 {report_type} 測試報告。

【RD 級審核框架 - 7 步】
1️⃣ 理解報告 - 標準、版本、補充規範
2️⃣ 驗證條件 - 環境、工況、樣品代表性
3️⃣ 檢查數據 - 規格、實測、判定邏輯
4️⃣ 覆蓋完整性 - 應測項目是否都測了
5️⃣ 矛盾檢測 - 結論與數據一致性
6️⃣ 風險評估 - 工程隱患識別
7️⃣ 最終判定 - PASS / FAIL / WARN / CONTRADICTION

【輸出格式】
## 報告基本資訊
- 採用標準：
- 測試工況：
- 樣品數量：

## 逐項審核
（詳細檢查）

## 風險評估
（工程視角隱患）

## 整體判定
**最終判定：PASS / FAIL / WARN / CONTRADICTION**"""

        user_prompt = f"""測試階段：{stage}
報告類型：{report_type}

請按照 RD 級框架分析以下報告文本：

{pdf_text[:15000]}"""

        result = call_openrouter_api(system_prompt, user_prompt)

        if not result:
            return jsonify({'status': 'error', 'message': 'API 調用失敗'}), 500

        # 自動判定
        verdict = 'PASS'
        if 'FAIL' in result.upper() and 'CONTRADICTION' not in result.upper():
            verdict = 'FAIL'
        elif 'WARN' in result.upper():
            verdict = 'WARN'
        elif 'CONTRADICTION' in result.upper():
            verdict = 'CONTRADICTION'

        return jsonify({
            'status': 'success',
            'filename': file.filename,
            'report_type': report_type,
            'stage': stage,
            'verdict': verdict,
            'result': result,
            'timestamp': datetime.now().isoformat()
        })

    except Exception as e:
        logger.error(f"審核失敗: {str(e)}")
        return jsonify({'status': 'error', 'message': str(e)}), 500

@app.route('/api/export/excel', methods=['POST'])
def export_excel():
    """導出為 Excel 格式（企業級）"""
    try:
        data = request.get_json()
        language = request.args.get('lang', 'zh_TW')
        
        if not data:
            return jsonify({'status': 'error', 'message': '缺少數據'}), 400
        
        exporter = ExcelExporter(data, language)
        content, filename = exporter.export()
        
        return send_file(
            BytesIO(content),
            mimetype='application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            as_attachment=True,
            download_name=filename
        )
    except Exception as e:
        logger.error(f"Excel 導出失敗: {str(e)}")
        return jsonify({'status': 'error', 'message': str(e)}), 500

@app.route('/api/export/html', methods=['POST'])
def export_html():
    """導出為 HTML 格式（企業級）"""
    try:
        data = request.get_json()
        language = request.args.get('lang', 'zh_TW')
        
        if not data:
            return jsonify({'status': 'error', 'message': '缺少數據'}), 400
        
        exporter = HTMLExporter(data, language)
        content, filename = exporter.export()
        
        return send_file(
            BytesIO(content),
            mimetype='text/html; charset=utf-8',
            as_attachment=True,
            download_name=filename
        )
    except Exception as e:
        logger.error(f"HTML 導出失敗: {str(e)}")
        return jsonify({'status': 'error', 'message': str(e)}), 500

